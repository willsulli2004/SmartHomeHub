"""Build and upload the alarm robot's firmware.

Run from the repo folder with the project's Python:

    .\\.venv\\Scripts\\python.exe firmware/robot/robot.py compile
    .\\.venv\\Scripts\\python.exe firmware/robot/robot.py usb COM7
    .\\.venv\\Scripts\\python.exe firmware/robot/robot.py ota
    .\\.venv\\Scripts\\python.exe firmware/robot/robot.py monitor COM7

    compile   build only, to check the code
    usb       build, then upload over the USB cable (the first flash must be this)
    ota       build, then upload over Wi-Fi to a robot that is switched on and idle
    monitor   show the robot's serial output

It uses the arduino-cli program that comes with the Arduino IDE, and the ESP32
board package already installed there. Nothing else is installed.

Settings come from firmware/robot/.env (see .env.example). Before each build they
are written to AlarmBot/secrets.h, which the sketch includes. Both files are
gitignored. Pass --example to build with .env.example instead, which is how the
code is compile-checked without real credentials.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SKETCH = HERE / "AlarmBot"
SECRETS_HEADER = SKETCH / "secrets.h"

# ESP32-S3-DevKitC-1 N16R8: 16 MB flash, 8 MB octal PSRAM. The partition scheme
# has two 3 MB app slots, which is what updating over Wi-Fi needs.
FQBN = "esp32:esp32:esp32s3:PSRAM=opi,FlashSize=16M,PartitionScheme=app3M_fat9M_16MB"

# Text settings become C strings; MQTT_PORT becomes a number.
TEXT_KEYS = ("WIFI_SSID", "WIFI_PASSWORD", "MQTT_HOST", "MQTT_USERNAME", "MQTT_PASSWORD", "OTA_PASSWORD")
REQUIRED = (*TEXT_KEYS, "MQTT_PORT")


def read_env(path: Path) -> dict[str, str]:
    """Read KEY=VALUE lines. Blank lines and lines starting with # are skipped."""
    if not path.is_file():
        raise SystemExit(f"{path} not found. Copy .env.example to .env in firmware/robot and fill it in.")
    values: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[key.strip()] = value
    return values


def c_string(value: str) -> str:
    """A value as a C string literal."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_secrets(values: dict[str, str]) -> None:
    """Write AlarmBot/secrets.h from the settings. Raises SystemExit naming anything missing."""
    missing = [key for key in REQUIRED if not values.get(key)]
    if missing:
        raise SystemExit("Missing in .env: " + ", ".join(missing))
    if not values["MQTT_PORT"].isdigit():
        raise SystemExit("MQTT_PORT in .env must be a number.")
    lines = [
        "// Generated by firmware/robot/robot.py from firmware/robot/.env. Do not edit and",
        "// do not commit: it holds the Wi-Fi, MQTT and update passwords. It is gitignored.",
        "#pragma once",
        "",
    ]
    lines += [f"#define SECRET_{key} {c_string(values[key])}" for key in TEXT_KEYS]
    lines += [f"#define SECRET_MQTT_PORT {int(values['MQTT_PORT'])}", ""]
    SECRETS_HEADER.write_text("\n".join(lines), encoding="utf-8")


def find_arduino_cli() -> str:
    """Locate arduino-cli: on the PATH, or inside the Arduino IDE's install folder."""
    found = shutil.which("arduino-cli")
    if found:
        return found
    candidates = [
        Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "Arduino IDE",
        Path(os.environ.get("ProgramFiles", "")) / "Arduino IDE",
    ]
    for base in candidates:
        cli = base / "resources" / "app" / "lib" / "backend" / "resources" / "arduino-cli.exe"
        if cli.is_file():
            return str(cli)
    raise SystemExit("arduino-cli not found. Install the Arduino IDE, or put arduino-cli on the PATH.")


def run(command: list[str], hide: str | None = None) -> None:
    """Run a command, showing it first. `hide` is a secret to keep out of what is shown."""
    shown = " ".join(command)
    if hide:
        shown = shown.replace(hide, "********")
    print(f"> {shown}", flush=True)
    result = subprocess.run(command, check=False)
    if result.returncode != 0:
        raise SystemExit(result.returncode)


def build_dir() -> Path:
    # Outside the repo and short: ESP32 builds make very long paths, which Windows rejects.
    return Path(os.environ.get("LOCALAPPDATA", str(Path.home()))) / "AlarmBotBuild"


def compile_sketch(cli: str) -> None:
    run([cli, "compile", "--fqbn", FQBN, "--build-path", str(build_dir()), "--warnings", "default", str(SKETCH)])


def main() -> None:
    parser = argparse.ArgumentParser(description="Build and upload the alarm robot's firmware.")
    parser.add_argument("action", choices=("compile", "usb", "ota", "monitor"))
    parser.add_argument("port", nargs="?", help="COM port for usb and monitor, for example COM7")
    parser.add_argument("--example", action="store_true", help="build with .env.example (no real credentials)")
    args = parser.parse_args()

    cli = find_arduino_cli()

    if args.action == "monitor":
        if not args.port:
            raise SystemExit("Give the COM port, for example: robot.py monitor COM7")
        run([cli, "monitor", "--port", args.port, "--config", "baudrate=115200"])
        return

    values = read_env(HERE / (".env.example" if args.example else ".env"))
    write_secrets(values)
    compile_sketch(cli)

    if args.action == "usb":
        if not args.port:
            raise SystemExit("Give the COM port, for example: robot.py usb COM7")
        run([cli, "upload", "--fqbn", FQBN, "--build-path", str(build_dir()), "--port", args.port, str(SKETCH)])
    elif args.action == "ota":
        if args.example:
            raise SystemExit("--example is for compile checks only; it cannot update a real robot.")
        address = values.get("ROBOT_ADDRESS") or "alarmbot.local"
        password = values["OTA_PASSWORD"]
        run(
            [
                cli, "upload", "--fqbn", FQBN, "--build-path", str(build_dir()),
                "--port", address, "--protocol", "network",
                "--upload-field", f"password={password}", str(SKETCH),
            ],
            hide=password,
        )


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        sys.exit(130)
